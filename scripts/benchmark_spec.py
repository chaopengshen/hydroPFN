"""Emit the benchmark definitions as a shareable table.

Generated FROM `hydropfn.data.protocol.BENCHMARKS` and the actual data, not
typed by hand, so the document cannot drift from what the code runs. Fold
sizes and scored-day counts are computed by loading the record.

    python scripts/benchmark_spec.py            # writes docs/ + results/
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from hydropfn.data import protocol as P                        # noqa: E402
from hydropfn.data.forcing import load_camels                  # noqa: E402
from hydropfn.paths import ROOT                                # noqa: E402

ARMS = [
    ("lstm", "Regional LSTM", "0.30M",
     "Forcings + static attributes, one LSTM across all training basins. "
     "Causal. Cannot read another basin. The field's reference bar."),
    ("unitA", "Unit A standalone (SiteEncoder)", "3.4M",
     "Same encoder as PUBModel but with NO connector and no context. "
     "Bidirectional. The honest no-context arm."),
    ("pubC", "PUBModel, concurrent context", "7.2M",
     "SiteEncoder + cross-site connector. Reads K neighbouring gauges' "
     "discharge on the SAME days being predicted (lag 0)."),
    ("pubL<N>", "PUBModel, lagged context", "7.2M",
     "As pubC, but the neighbours' records stop N days before the prediction "
     "day. The window keeps its full 512 d of history, so lag and history "
     "length are independent. N in {1,3,7,16,32,64,128}."),
]

BASELINES = [
    ("nn_donor", "Copy the single nearest gauge's hydrograph. Flat in K."),
    ("ctx_mean", "Unweighted mean of the K neighbours' discharge."),
    ("idw", "Inverse-distance-weighted mean of the K neighbours (1/d^2). "
            "No training, no parameters. The bar K>0 must beat."),
]


def main():
    d = load_camels(P.CAMELS_NC)
    rows = []
    for name, b in P.BENCHMARKS.items():
        sub, gage = P.load_subset(d, b["basins"])
        w = P.windows(d["time"], name)
        for ext in b["extents"]:
            fs = P.folds(ext, gage)
            rows.append({
                "benchmark": name,
                "label": b["label"],
                "extent": ext,
                "basins": b["basins"],
                "train_start": b["train"][0], "train_end": b["train"][1],
                "test_start": b["test"][0], "test_end": b["test"][1],
                "train_days": w["train"].stop - w["train"].start,
                "scored_days": w["score"].stop - w["score"].start,
                "warmup_days": P.WARMUP,
                "n_folds": len(fs),
                "fold_sizes": " ".join(str(len(f)) for f in fs),
                "note": b["note"],
            })

    out_csv = ROOT / "results" / "benchmark_spec.csv"
    out_csv.parent.mkdir(parents=True, exist_ok=True)
    with open(out_csv, "w", newline="") as f:
        wtr = csv.DictWriter(f, fieldnames=list(rows[0]))
        wtr.writeheader(); wtr.writerows(rows)

    L = []
    L.append("# CAMELS benchmark suite — what each test is\n")
    L.append("Generated by `scripts/benchmark_spec.py` from "
             "`hydropfn.data.protocol.BENCHMARKS`.\n")
    L.append("Metric throughout: **median per-basin NSE on raw discharge "
             "(mm/day)**, computed by dmg_dev's own `Metrics` class "
             "(vendored verbatim). 365 days of spin-up precede every scored "
             "period and are never scored.\n")

    L.append("\n## The benchmarks\n")
    L.append("| Benchmark | Name | Basins | Holdout | Train | Test | Scored days | Folds (sizes) |")
    L.append("|---|---|---|---|---|---|---|---|")
    for r in rows:
        L.append(f"| `{r['benchmark']}` | {r['label']} | {r['basins']} | "
                 f"{r['extent']} | {r['train_start']} → {r['train_end']} | "
                 f"{r['test_start']} → {r['test_end']} | {r['scored_days']:,} | "
                 f"{r['n_folds']} ({r['fold_sizes']}) |")

    L.append("\n### Notes per benchmark\n")
    seen = set()
    for r in rows:
        if r["benchmark"] in seen:
            continue
        seen.add(r["benchmark"])
        L.append(f"- **`{r['benchmark']}` — {r['label']}**: {r['note']}")

    L.append("\n## Holdout types\n")
    L.append("| Type | What is held out | Folds |")
    L.append("|---|---|---|")
    L.append("| **PUB** | 10 random basin groups, leave-one-group-out. Held-out "
             "basins are scattered, so a query's geographic neighbours are "
             "mostly *training* basins — \"an ungauged basin among gauged "
             "ones\". | 10 |")
    L.append("| **PUR** | 7 contiguous regions, leave-one-region-out. The whole "
             "region is out, so neighbours are mostly other *held-out* basins "
             "the model never trained on. The harder transfer test. | 7 |")
    L.append("| **temporal** | No spatial holdout — every basin is trained on "
             "and scored. The periods separate train from test. | 1 |")

    L.append("\n## Model arms\n")
    L.append("| Arm | Model | Params | What it sees |")
    L.append("|---|---|---|---|")
    for tag, nm, pr, desc in ARMS:
        L.append(f"| `{tag}` | {nm} | {pr} | {desc} |")

    L.append("\n**K** = number of neighbouring gauges the model reads at "
             "inference. `K=0` is the same information a regional LSTM has and "
             "is the row directly comparable to it; `K>0` adds neighbour "
             "discharge, which an LSTM structurally cannot use.\n")

    L.append("\n## Donor baselines (reported beside every K>0 row)\n")
    L.append("| Baseline | What it does |")
    L.append("|---|---|")
    for tag, desc in BASELINES:
        L.append(f"| `{tag}` | {desc} |")

    L.append("\n## Caveats that belong with any quoted number\n")
    L.append("- **Single seed.** Treat margins under ~0.015 as ties.")
    L.append("- **No pretraining.** Every model is trained from random init, "
             "one per fold. `load_stefaland_trunk` is never called, while two "
             "of the three dmg_dev reference rows *are* pretrained arms.")
    L.append("- **Two asymmetries favour PUBModel** over the LSTM: it is a "
             "bidirectional smoother where the LSTM is causal, and it reads "
             "neighbours' discharge where the LSTM cannot.")
    L.append("- **PUR region labels are wrong** in the source CSV (the `huc` "
             "column disagrees with the station ids for 467 of 531 basins). "
             "The blocks are valid and disjoint; only the names lie. Call them "
             "R0–R6, not \"Pacific Northwest\".")
    L.append("- **The LSTM overfits with budget** (PUB 0.654 @50ep → 0.628 "
             "@200ep), while the transformer arms improve. Compare at matched "
             "epochs and say which.")

    out_md = ROOT / "docs" / "benchmark_spec.md"
    out_md.write_text("\n".join(L) + "\n")
    print(f"wrote {out_csv}")
    print(f"wrote {out_md}")


if __name__ == "__main__":
    main()
