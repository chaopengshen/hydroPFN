"""Write the CAMELS results as a narrative markdown report.

Reproduces: docs/camels_results.md

Generated from logs/camels531/*/run.json so the tables cannot drift from the
runs. Every table states its budget and seed count, because this project's
expensive mistakes have all been comparisons across protocols or budgets that
looked like comparisons across models.

    python scripts/results_report.py
"""
